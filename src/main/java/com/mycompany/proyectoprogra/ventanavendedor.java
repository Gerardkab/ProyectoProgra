    public void tabla(){
    DefaultTableModel t = new DefaultTableModel(new String[]{"Calle","Avenida","Dirreccion completa","Zona"},ProyectoProgra.dire.size());
    jTable1.setModel(t);
    
    TableModel tabla = jTable1.getModel();
    for(int i = 0; i<ProyectoProgra.dire.size();i++){
    cambioexa ca = ProyectoProgra.dire.get(i);
    tabla.setValueAt(ca.calle, i,0);
    tabla.setValueAt(ca.avenida, i,1);
    tabla.setValueAt(ca.direccion, i,2);
    tabla.setValueAt(ca.zona, i,3);
    
    }     
      }
    
    
