    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        //TODO add your handling code here:
        String nuevacontra = jTextField1.getText();

        if(!nuevacontra.matches("^(?=.*[A-Z])(?=.*\\d).{6,}$")) {
            JOptionPane.showMessageDialog(this, "La contraseña debe contener al menos una letra mayúscula, un número y contega 6 caracteres");
            return;
        }
        String confircontra = jTextField2.getText();
        if(!nuevacontra.equals(confircontra)){
            JOptionPane.showMessageDialog(this,"Las contraseñas no coinciden");

            return;
        }

        usuarioactual.contra = nuevacontra;
        JOptionPane.showMessageDialog(this,"La contraseña se actualizo Correctamente");

        jTextField1.setText("");
        jTextField2.setText("");

    }//GEN-LAST:event_jButton1ActionPerformed

