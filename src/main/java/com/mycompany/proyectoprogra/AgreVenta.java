    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        String titulolib = jComboBox1.getSelectedItem().toString();
        int cantidad = Integer.parseInt(jTextField2.getText());

        for (libros libro : ProyectoProgra.libros) {
            if (libro.titulo.equals(titulolib)) {
                if (libro.cantidad >= cantidad) {

                    articulos ve = new articulos();

                    DecimalFormatSymbols separador = new DecimalFormatSymbols();
                    separador.setDecimalSeparator('.');
                    DecimalFormat df = new DecimalFormat("0.00", separador);

                    ve.cant = cantidad;
                    ve.libro = titulolib;
                    ve.total = txtTotalM.getText();
                    ve.totalsinIva = txtTotalMe.getText();
                    ve.fecha = txtFecha.getText();
                    ve.precio = txtPrecio.getText();

                    ProyectoProgra.art.add(ve);
                    ProyectoProgra.artvendidos.add(ve);

                    dibujartabla();

                    calculos();

                    jTextField2.setText("");
                    txtTotalMe.setText("Q 00.00");
                    txtTotalM.setText("Q 00.00");
                    txtIVA.setText("Q 00.00");
                } else {
                    JOptionPane.showMessageDialog(this, "No hay suficiente unidades de este libro\nUnidades disponibles: " + libro.cantidad);
                }
                break;
            }
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

