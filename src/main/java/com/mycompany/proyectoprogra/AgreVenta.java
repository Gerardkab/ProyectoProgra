        txtNIT.setText("");
        txtDirec.setText("");
        jTextField2.setText("");
        txtTotalMe.setText("Q 00.00");
        txtTotalM.setText("Q 00.00");
        txtIVA.setText("Q 00.00");

        ProyectoProgra.art.clear();

        limpiartabla();

