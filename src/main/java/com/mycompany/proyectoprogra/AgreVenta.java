    private void calculos() {
        DecimalFormatSymbols separador = new DecimalFormatSymbols();
        separador.setDecimalSeparator('.');
        DecimalFormat df = new DecimalFormat("0.00", separador);

        double sumatotalconiva = 0;
        double sumatotalsiniva = 0;

        for (articulos venta : ProyectoProgra.art) {

            String sinIVA = venta.totalsinIva.replace("Q", "").trim();
            String conIVA = venta.total.replace("Q", "").trim();

            sumatotalsiniva += Double.parseDouble(sinIVA);
            sumatotalconiva += Double.parseDouble(conIVA);
        }

        txtTotalFinalSinIVA.setText("Q " + df.format(sumatotalsiniva));
        txtTotalFinal.setText("Q " + df.format(sumatotalconiva));
    }

