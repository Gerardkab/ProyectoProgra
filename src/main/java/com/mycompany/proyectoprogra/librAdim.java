        public void dibujartabla(){
        
        DefaultTableModel t = new DefaultTableModel(new String[]{"TITULO","AUTOR","GENERO","PRECIO","CANTIDAD"},ProyectoProgra.libros.size());
        jTable1.setModel(t);
        
        TableModel tabla = jTable1.getModel();
        for(int i = 0; i<ProyectoProgra.libros.size();i++){
            libros l = ProyectoProgra.libros.get(i);
            tabla.setValueAt(l.titulo, i, 0);
            tabla.setValueAt(l.autor, i, 1);
            tabla.setValueAt(l.genero, i, 2);
            tabla.setValueAt(l.precios, i, 3);
            tabla.setValueAt(l.cantidad, i, 4);
                        
        }

    }

