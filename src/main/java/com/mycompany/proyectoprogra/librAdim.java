    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:

        int editar = jTable1.getSelectedRow();
        if(editar >-1){

                libros = ProyectoProgra.libros.get(editar);

                jTextField1.setText(libros.titulo);
                jTextField2.setText(libros.autor);
                jTextField3.setText(libros.genero);
                jTextField5.setText(String.valueOf(libros.precios));
                jTextField4.setText(String.valueOf(libros.cantidad));
                
        }
        
        else{
        JOptionPane.showMessageDialog(this,"Seleccione un elemento para editar");
    }
        
        
    }//GEN-LAST:event_jButton3ActionPerformed

