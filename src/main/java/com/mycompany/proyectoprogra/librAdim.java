    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if(libros!=null){
           
            libros.titulo = jTextField1.getText();
            libros.autor = jTextField2.getText();
            libros.genero =jTextField3.getText();
            libros.precios = Double.parseDouble(jTextField5.getText());
            libros.cantidad = Integer.parseInt(jTextField4.getText());
            
        }
        JOptionPane.showMessageDialog(this, "El elemento se ha modificado correctamente");
        dibujartabla();
        
    }//GEN-LAST:event_jButton1ActionPerformed

